const genericError: Record<Locale, string> = {
  en: "The request failed (code: {code}).",
  fr: "La requête a échoué (code : {code}).",
  de: "Die Anfrage ist fehlgeschlagen (Code: {code}).",
  ro: "Cererea a eșuat (cod: {code}).",
};

const detailsLabel: Record<Locale, string> = { en: "Details", fr: "Détails", de: "Details", ro: "Detalii" };

const withDetail = (locale: Locale, text: string, detail: string) =>
  detail ? `${text} ${detailsLabel[locale]}: ${detail}` : text;

/**
 * Text for the error banner in the selected language.
 * API errors use their code's sentence plus any diagnostic; unknown codes use a
 * generic sentence naming the code; already-localized strings pass through.
 */
export function describeError(locale: Locale, failure: unknown): string {
  if (failure instanceof ApiError) {
    const known = errorMessages[locale][failure.code];
    const text = known ?? genericError[locale].replace("{code}", failure.code);
    return withDetail(locale, text, failure.detail);
  }
  if (failure instanceof Error) return withDetail(locale, errorMessages[locale].request_failed, failure.message);
  return failure == null ? "" : String(failure);
}
